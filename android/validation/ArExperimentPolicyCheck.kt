package com.yeogirokarpoc.geo

fun main() {
    var checks = 0
    fun expect(value: Boolean, label: String) { check(value) { label }; checks++ }
    expect(!ArExperimentPolicy.acceptsHit(0.19f), "Too-close hits must be rejected")
    expect(ArExperimentPolicy.acceptsHit(0.2f), "Near boundary")
    expect(ArExperimentPolicy.acceptsHit(5f), "Far boundary")
    expect(!ArExperimentPolicy.acceptsHit(5.01f), "Far hits must be rejected")
    expect(!ArExperimentPolicy.acceptsHit(Float.NaN), "Non-finite hit")
    expect(!ArExperimentPolicy.freshLocation(-1, 1f, true), "Future location timestamp")
    expect(ArExperimentPolicy.freshLocation(10_000, 5f, true), "Location freshness boundary")
    expect(!ArExperimentPolicy.freshLocation(10_001, 5f, true), "Stale location")
    expect(!ArExperimentPolicy.freshLocation(0, 0f, false), "Missing accuracy is not zero uncertainty")
    expect(!ArExperimentPolicy.freshLocation(0, Float.NaN, true), "Non-finite accuracy")
    expect(!ArExperimentPolicy.freshLocation(0, -1f, true), "Negative accuracy")
    val gate = CloudQualityGate()
    expect(!cloudQualityAllowsHost("INSUFFICIENT", true, false, false), "Default policy rejects low quality")
    expect(cloudQualityAllowsHost("INSUFFICIENT", true, false, true), "Explicit experiment preserves low-quality trial")
    expect(cloudQualityAllowsHost("SUFFICIENT", true, false, true), "Explicit sufficient-quality trial")
    expect(!cloudQualityAllowsHost("GOOD", false, true, true), "Experiment cannot use stale quality after tracking loss")
    expect(!cloudQualityAllowsHost("ERROR", true, false, true), "Experiment cannot bypass quality measurement errors")
    expect(!cloudQualityAllowsHost("GOOD", true, false, false), "Default policy still requires hold")
    expect(cloudQualityAllowsHost("GOOD", true, true, false), "Default stable GOOD is accepted")
    expect(!gate.update(0, true), "First GOOD sample must not enable host")
    gate.update(250, true); gate.update(500, true)
    expect(!gate.update(750, true), "Hold has not elapsed")
    expect(gate.update(1000, true), "Sustained GOOD enables host")
    expect(!gate.update(1100, false), "Tracking loss or poor quality disables host")
    expect(!gate.update(1200, true), "Recovery requires another full hold")
    expect(!gate.update(5000, true), "Long frame gap must not count as observed GOOD")
    expect(!gate.update(100, true), "Backward clock restarts hold")
    gate.reset()
    expect(!gate.update(6000, true), "New placement clears previous quality history")
    expect(relativeDirection(floatArrayOf(0f, 0f, -1f)) == "↑ 정면", "ARCore forward is negative Z")
    expect(relativeDirection(floatArrayOf(1f, 0f, 0f))!!.startsWith("→"), "Camera right")
    expect(relativeDirection(floatArrayOf(-1f, 0f, 0f))!!.startsWith("←"), "Camera left")
    expect(relativeDirection(floatArrayOf(0f, 0f, 1f))!!.startsWith("↶"), "Behind camera")
    expect(relativeDirection(floatArrayOf(Float.NaN, 0f, 0f)) == null, "Bad pose has no direction")
    println("ArExperimentPolicy: $checks checks passed")
}
